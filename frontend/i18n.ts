const DICTS: Record<Locale, Record<keyof typeof PT_BR, string>> = {
  "pt-BR": PT_BR,
  en: EN,
}

function detectLocale(): Locale {
  const preference = getLanguagePreference()
  if (preference === "pt-BR" || preference === "en") return preference
  const language = `${document?.documentElement?.lang ?? ""} ${navigator?.language ?? ""} ${(navigator?.languages ?? []).join(" ")}`
    .toLowerCase()
  return language.includes("pt") ? "pt-BR" : "en"
}

export function currentLocale(): Locale {
  return detectLocale()
}

export function t(key: keyof typeof PT_BR, vars: Record<string, string | number> = {}): string {
  const value = DICTS[detectLocale()][key] ?? PT_BR[key] ?? key
  return value.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? ""))
}
